-- RefundGuard.AI  V2: RBAC users, risk assessments, hold-and-release reviews (Oracle 21c/23c)
--
-- You normally do NOT need to run this: the app uses spring.jpa.hibernate.ddl-auto=update, which creates
-- the three new tables on startup, and SchemaUpgradeRunner relaxes the old rg_refunds status CHECK constraint.
-- This script is the equivalent for environments where DDL is applied manually (ddl-auto=validate/none).
-- It only ADDS objects; existing rows in rg_refunds / rg_cases / rg_refund_events / rg_orders are untouched.
-- STATUS: written to mirror the JPA mappings; NOT executed against a real Oracle instance in this delivery.

CREATE TABLE rg_users (
    id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR2(64 CHAR)  NOT NULL,
    password_hash VARCHAR2(100 CHAR) NOT NULL,
    user_role     VARCHAR2(20 CHAR)  NOT NULL CHECK (user_role IN ('OPERATOR','REVIEWER','ADMIN')),
    enabled       NUMBER(1)          DEFAULT 1 NOT NULL,
    created_at    TIMESTAMP(6),
    updated_at    TIMESTAMP(6),
    CONSTRAINT uk_rg_users_username UNIQUE (username)
);

CREATE TABLE rg_risk_assessments (
    id                 NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refund_id          NUMBER             NOT NULL,
    risk_score         NUMBER(10)         NOT NULL,
    risk_level         VARCHAR2(20 CHAR)  NOT NULL CHECK (risk_level IN ('LOW','MEDIUM','HIGH','CRITICAL')),
    assessed_at        TIMESTAMP(6)       NOT NULL,
    engine_version     VARCHAR2(40 CHAR)  NOT NULL,
    input_fingerprint  VARCHAR2(64 CHAR),
    config_fingerprint VARCHAR2(64 CHAR),
    assessment_trigger VARCHAR2(30 CHAR),
    indicators_json    VARCHAR2(4000 CHAR),
    not_evaluated_json VARCHAR2(2000 CHAR)
);
CREATE INDEX ix_rg_risk_refund ON rg_risk_assessments (refund_id);

CREATE TABLE rg_refund_reviews (
    id                     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    row_version            NUMBER,
    refund_id              NUMBER            NOT NULL,
    status                 VARCHAR2(20 CHAR) NOT NULL CHECK (status IN ('PENDING','APPROVED','REJECTED','SUPERSEDED')),
    previous_status        VARCHAR2(30 CHAR),
    hold_assessment_id     NUMBER,
    hold_reason            VARCHAR2(1000 CHAR),
    held_at                TIMESTAMP(6)      NOT NULL,
    decision               VARCHAR2(20 CHAR) CHECK (decision IN ('APPROVE','REJECT')),
    decided_by             VARCHAR2(64 CHAR),
    decided_by_role        VARCHAR2(20 CHAR),
    decision_reason        VARCHAR2(1000 CHAR),
    decided_at             TIMESTAMP(6),
    decision_assessment_id NUMBER,
    simulated_release      NUMBER(1)
);
CREATE INDEX ix_rg_review_refund ON rg_refund_reviews (refund_id);

-- rg_refunds.derived_status gains two enum values (ON_HOLD, REJECTED). Databases created by older versions have a
-- CHECK constraint that does not list them; drop it (Hibernate does not re-add CHECK constraints on existing tables).
BEGIN
  FOR c IN (SELECT constraint_name FROM user_constraints
             WHERE table_name = 'RG_REFUNDS' AND constraint_type = 'C'
               AND UPPER(search_condition_vc) LIKE '%DERIVED_STATUS%IN%'
               AND (UPPER(search_condition_vc) NOT LIKE '%ON_HOLD%' OR UPPER(search_condition_vc) NOT LIKE '%REJECTED%')) LOOP
    EXECUTE IMMEDIATE 'ALTER TABLE rg_refunds DROP CONSTRAINT ' || c.constraint_name;
  END LOOP;
END;
/

