-- RefundGuard.AI  V4: explainable risk scoring - per-rule factor rows (Oracle 21c/23c)
--
-- You normally do NOT need to run this: with spring.jpa.hibernate.ddl-auto=update Hibernate creates rg_risk_factors
-- and adds rg_risk_assessments.policy_violation on startup. This script is the equivalent for environments where DDL
-- is applied manually (ddl-auto=validate/none). It only ADDS objects; existing rows are untouched.
--   * Existing (RULE_BASED_V1) assessments keep their factors in rg_risk_assessments.indicators_json and are still
--     readable; the application marks them "outdated" (older rule version) until they are reassessed.
--   * New (RULE_BASED_V2) assessments store one row per triggered rule in rg_risk_factors and leave indicators_json NULL.
-- STATUS: written to mirror the JPA mappings; NOT executed against a real Oracle instance in this delivery.

ALTER TABLE rg_risk_assessments ADD (policy_violation NUMBER(1) CHECK (policy_violation IN (0, 1)));

CREATE TABLE rg_risk_factors (
    id               NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessment_id    NUMBER              NOT NULL,
    ordinal          NUMBER(10)          NOT NULL,
    rule_code        VARCHAR2(50 CHAR)   NOT NULL,
    points           NUMBER(10)          NOT NULL CHECK (points BETWEEN 0 AND 100),
    reason           VARCHAR2(500 CHAR)  NOT NULL,
    evidence_json    VARCHAR2(1000 CHAR),
    policy_violation NUMBER(1)           DEFAULT 0 NOT NULL CHECK (policy_violation IN (0, 1)),
    CONSTRAINT fk_rg_risk_factor_assess FOREIGN KEY (assessment_id)
        REFERENCES rg_risk_assessments (id) ON DELETE CASCADE
);
CREATE INDEX ix_rg_risk_factor_assess ON rg_risk_factors (assessment_id);
CREATE INDEX ix_rg_risk_factor_code   ON rg_risk_factors (rule_code);

-- Supports "latest assessment per refund" (max(id) by refund_id) used by the admin analytics queries.
CREATE INDEX ix_rg_risk_refund_id ON rg_risk_assessments (refund_id, id);

